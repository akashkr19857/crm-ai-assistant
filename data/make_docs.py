def write_pdf(path: Path, title: str, sections: list[tuple[str, list[str]]]) -> None:
    html = [f"<h1>{title}</h1><p><i>{NOTICE}</i></p>"]
    for heading, paras in sections:
        html.append(f"<h2>{heading}</h2>" + "".join(f"<p>{p}</p>" for p in paras))
    story = pymupdf.Story(html="".join(html), user_css="body{font-family:sans-serif;font-size:11pt} h1{font-size:20pt} h2{font-size:14pt;margin-top:14pt}")
    writer = pymupdf.DocumentWriter(str(path))
    mediabox = pymupdf.paper_rect("letter")
    more = True
    while more:
        dev = writer.begin_page(mediabox)
        more, _ = story.place(mediabox + (54, 54, -54, -54))
        story.draw(dev)
        writer.end_page()
    writer.close()
    with pymupdf.open(path) as d:
        d.set_metadata({"title": title, "author": "NimbusCRM (fictional)"})
        d.saveIncr()


def main() -> None:
    manifest = []
    for folder, docs in DOCS.items():
        out = HERE / "docs" / folder
        out.mkdir(parents=True, exist_ok=True)
        ws = "product-docs" if folder == "product" else "sales-playbook"
        for name, title, sections in docs:
            write_pdf(out / name, title, sections)
            manifest.append({"path": f"data/docs/{folder}/{name}", "workspace": ws, "title": title,
                             "source": "generated by data/make_docs.py (fictional)"})
    (HERE / "manifest.json").write_text(json.dumps(manifest, indent=1), encoding="utf-8")
    print(f"wrote {len(manifest)} documents")


if __name__ == "__main__":
    main()
